# Standalone test
# ----------------------------------------------------------------------

def _demo():
    """
    Standalone generator test.

    This does not start the FastAPI dashboard. It simply checks whether the
    generator can discover different model prediction classes.
    """

    import logging
    from collections import Counter
    import queue

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(message)s",
    )

    q = queue.Queue()

    generator = SyntheticFlowGenerator(
        q,
        interval=0.1,
    )

    print()
    print("=" * 70)
    print("Synthetic flow generator test")
    print("=" * 70)
    print()

    results = Counter()

    for index in range(100):

        flow = generator.generate_flow()

        try:
            predicted, confidence, _ = generator._preprocessor.predict(flow)
        except Exception:
            predicted = "ERROR"
            confidence = 0.0

        results[predicted] += 1

        print(
            f"{index + 1:03d} | "
            f"predicted={predicted:<6} | "
            f"confidence={confidence:.3f} | "
            f"target={flow.get('_synthetic_scenario')}"
        )

    print()
    print("=" * 70)
    print("Prediction distribution")
    print("=" * 70)

    for label, count in sorted(results.items()):
        print(f"{label:<10}: {count}")

    print()


if __name__ == "__main__":
    _demo()
    